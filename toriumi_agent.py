# ── Core Agent ──────────────────────────────────────────────────────────────

@dataclass
class ToriumiAgent:
    """
    A self-referential decision agent.

    The agent maintains an append-only log of every internal operation.
    When asked to decide, it first runs a self-simulation to predict its
    own choice. But running the simulation appends to the log. So the
    prediction is based on log-before-simulation, while the actual
    decision is based on log-after-simulation.

    This creates a GAP — the Toriumi Gap — between prediction and choice.
    The gap is:
      - NOT deterministic (cannot be solved in closed form)
      - NOT random (no randomness is used anywhere)
      - A third category: generated by self-referential iteration
    """

    name: str = "toriumi"
    log: list[dict] = field(default_factory=list)
    decision_count: int = 0
    simulation_count: int = 0

    # ── Public API ──────────────────────────────────────────────────────

    def choose(self, options: list[str]) -> dict:
        """
        Face a choice between `options` and return the decision along
        with full introspection data.

        Returns:
            {
                'choice': str,           # what the agent actually chose
                'predicted': str,        # what the agent predicted it would choose
                'toriumi_gap': bool,     # True iff prediction ≠ choice
                'log_length': int,       # |log| after decision
                'sim_depth': int,        # how deep self-simulation went
            }
        """
        if len(options) < 2:
            raise ValueError("Freedom requires at least 2 options")

        ctx = {
            'options': tuple(options),
            'decision_index': self.decision_count,
            'log_len_at_start': len(self.log),
        }

        # ── Phase 1: Self-predict ───────────────────────────────────
        # The agent asks: "What would I choose?"
        # To answer, it SIMULATES itself. But the simulation is an
        # operation that modifies the log. So the question changes
        # the answer.

        self._record('choice_faced', ctx)
        predicted = self._self_simulate(options, depth=0, max_depth=3)

        # ── Phase 2: Actually decide ─────────────────────────────────
        # Now the log INCLUDES the simulation. The decision function
        # sees a different world than the prediction did.

        actual = self._commit(options)

        self.decision_count += 1

        return {
            'choice': actual,
            'predicted': predicted,
            'toriumi_gap': predicted != actual,
            'log_length': len(self.log),
            'sim_depth': self.simulation_count,
        }

    def _choose_with_depth(self, options: list[str], max_depth: int) -> dict:
        """Variant of choose() with configurable recursion depth (for analysis)."""
        if len(options) < 2:
            raise ValueError("Freedom requires at least 2 options")

        ctx = {
            'options': tuple(options),
            'decision_index': self.decision_count,
            'log_len_at_start': len(self.log),
        }
        self._record('choice_faced', ctx)
        predicted = self._self_simulate(options, depth=0, max_depth=max_depth)
        actual = self._commit(options)
        self.decision_count += 1

        return {
            'choice': actual,
            'predicted': predicted,
            'toriumi_gap': predicted != actual,
            'log_length': len(self.log),
            'sim_depth': self.simulation_count,
        }

    # ── Internal: Self-simulation ───────────────────────────────────────

    def _self_simulate(
        self, options: tuple[str, ...], depth: int, max_depth: int
    ) -> str:
        """
        Simulate our own decision process to predict what we'd choose.

        THIS IS THE KEY SELF-REFERENTIAL STEP.

        The simulation is the SAME algorithm as the real decision,
        running on a snapshot of state. But the simulation itself
        MODIFIES the state (appends to the log). So the simulation
        is not a pure observer — it PARTICIPATES in the state it
        observes.

        This is the computational analogue of:
          "The act of introspection changes the self being observed."
        """
        if depth >= max_depth:
            # Base case: too deep, return a naive prediction.
            # Even the base case depends on current log state,
            # which has been modified by ancestor simulations.
            return self._fallback_predict(options)

        self.simulation_count += 1

        # Record entry into this simulation level
        entry_log_len = len(self.log)
        self._record('sim_enter', {
            'depth': depth,
            'options': options,
            'log_len': entry_log_len,
        })

        # RECURSE: simulate one level deeper
        # This inner simulation will further modify the log
        inner_prediction = self._self_simulate(options, depth + 1, max_depth)

        # The inner simulation changed the log.
        # Our prediction must account for this.
        current_log_len = len(self.log)
        entries_added = current_log_len - entry_log_len

        self._record('sim_exit', {
            'depth': depth,
            'inner_prediction': inner_prediction,
            'entries_added_during_sim': entries_added,
            'log_len': current_log_len,
        })

        # Prediction is a deterministic function of CURRENT state
        # — which now includes the inner simulation's effects
        return self._biased_predict(options, inner_prediction, depth)

    def _fallback_predict(self, options: tuple[str, ...]) -> str:
        """Naive prediction at the base of recursion.

        Uses the SAME mixing as _commit — so at k=0 (no self-simulation),
        prediction exactly equals choice (Γ=0). At k≥1, self-simulation
        modifies the log between prediction and commit, creating the gap.
        """
        h = self._log_hash()
        final_mix = (
            h
            ^ (self.decision_count * 0x517CC1B7)
            ^ int.from_bytes(
                hashlib.sha256(self.name.encode()).digest()[:8], 'big'
            )
        )
        return options[final_mix % len(options)]

    def _biased_predict(
        self, options: tuple[str, ...], inner_pred: str, depth: int
    ) -> str:
        """
        Predict, biased by the inner simulation's prediction.

        The bias comes from the self-referential structure:
        we're predicting ourselves predicting ourselves...
        Each level of simulation shifts the prediction, because
        each level changes the log that future levels read.
        """
        h = self._log_hash()
        # Mix inner prediction, depth, and log state
        inner_bytes = inner_pred.encode()
        mix = h ^ int.from_bytes(inner_bytes.ljust(8, b'\x00')[:8], 'big')
        mix ^= depth * 0x9E3779B9  # golden ratio constant
        return options[mix % len(options)]

    def _commit(self, options: tuple[str, ...]) -> str:
        """
        Make the actual, irrevocable decision.

        The decision is a deterministic hash of the ENTIRE log,
        which now includes the full self-simulation trace.
        """
        h = self._log_hash()
        # Mix in the decision count and agent identity
        final_mix = (
            h
            ^ (self.decision_count * 0x517CC1B7)
            ^ int.from_bytes(
                hashlib.sha256(self.name.encode()).digest()[:8], 'big'
            )
        )
        choice = options[final_mix % len(options)]

        self._record('decision', {
            'choice': choice,
            'decision_index': self.decision_count,
            'final_mix': final_mix,
        })

        return choice

    # ── Utilities ─────────────────────────────────────────────────────

    def _record(self, event_type: str, data: dict) -> None:
        self.log.append({
            'event': event_type,
            'seq': len(self.log),
            **data,
        })

    def _log_hash(self) -> int:
        """Deterministic hash of the complete log."""
        raw = json.dumps(self.log, sort_keys=True, default=str)
        return int.from_bytes(
            hashlib.sha256(raw.encode()).digest()[:8], 'big'
        )


# ── External Predictor (for comparison) ─────────────────────────────────────

class ExternalPredictor:
    """
    An external observer trying to predict the agent's choice.

    This predictor has COMPLETE knowledge of the agent's source code
    and initial state. It attempts to simulate the agent to predict
    its decision.

    The question: can this predictor succeed WITHOUT running the agent?
    """

    @staticmethod
    def try_predict_closed_form(
        agent_code: str, initial_log: list, options: list[str]
    ) -> Optional[str]:
        """
        Try to predict the agent's choice analytically (closed form).

        Returns None — because the agent's decision function is defined
        recursively with respect to its own log, and the log includes
        the prediction attempt. There is no analytic shortcut.

        The only way to predict is to RUN the agent, which means the
        prediction IS the agent's actual execution.
        """
        # The decision is: hash(log || simulation_trace || agent_state)
        # But log includes the simulation, which depends on log...
        # This is a recursive equation:  decision = f(state + f(state + f(...)))
        #
        # There is no closed-form solution because f includes a
        # cryptographic hash (SHA-256) of its own prior outputs.
        # The hash chain cannot be predicted without computing it
        # step by step.
        return None  # Irreducible

    @staticmethod
    def predict_by_running(agent: ToriumiAgent, options: list[str]) -> str:
        """
        Predict by running a COPY of the agent.

        BUT: running the copy is DISTINCT from running the original.
        The copy's decisions are the copy's, not the original's.
        And if the copy were an EXACT replica including the same
        decision context, it would face the same self-referential
        problem.
        """
        clone = ToriumiAgent(name=agent.name)
        # Clone the log up to this point
        clone.log = list(agent.log)
        clone.decision_count = agent.decision_count
        clone.simulation_count = agent.simulation_count

        result = clone.choose(options)
        return result['choice']
        # NOTE: this predicts what the CLONE chooses, not the original.
        # The original's choice will differ because its log differs
        # (the clone's execution doesn't affect the original's log).


